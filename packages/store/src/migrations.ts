/**
 * Versioned schema migrations — the only way the schema changes.
 *
 * A production database is never edited by hand: a schema change is a new
 * entry at the end of `MIGRATIONS`, merged like any other code, and applied by
 * `store.migrate()` on the next deploy (Railway runs `cli.js migrate` as the
 * pre-deploy step; every CLI command and the API boot run it too). Applied ids
 * are recorded in `schema_migrations`, so each migration runs exactly once per
 * database, in order, inside its own transaction.
 *
 * Rules:
 * - **Append only.** Never edit or reorder a migration that has shipped; a
 *   database that already applied it will never see the change. Fix forward.
 * - **Portable SQL.** Plain SQL valid in SQLite and Postgres. The genuine
 *   dialect differences — identity columns, 8-byte floats, byte-order text —
 *   are the `ID`, `FLOAT` and `TEXT` tokens from `types()`; use them for every
 *   new column. Anything else that differs goes through a `ctx` helper (see
 *   `addColumnIfMissing`) rather than a dialect branch in a migration body.
 * - `INSERT … ON CONFLICT DO UPDATE` only, TEXT for dates, no extensions.
 */

export type Dialect = 'sqlite' | 'postgres';

export interface MigrationContext {
  readonly dialect: Dialect;
  exec(sql: string): Promise<void>;
  columnExists(table: string, column: string): Promise<boolean>;
}

export interface Migration {
  id: number;
  name: string;
  up(ctx: MigrationContext): Promise<void>;
}

/** Dialect-specific spellings of the column types that differ. */
export function types(dialect: Dialect): { ID: string; FLOAT: string; TEXT: string } {
  return dialect === 'postgres'
    ? {
      // BY DEFAULT rather than ALWAYS so `copy-store` can carry ids across verbatim.
      ID: 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
      // Postgres REAL is a 4-byte float, which would silently lose precision.
      FLOAT: 'DOUBLE PRECISION',
      // Byte order, as SQLite sorts. A glibc/ICU locale collation ignores
      // punctuation, so `us_a` would sort before `us.a_b` — every ORDER BY on
      // an id would then depend on how the host happened to initdb.
      TEXT: 'TEXT COLLATE "C"',
    }
    : { ID: 'INTEGER PRIMARY KEY AUTOINCREMENT', FLOAT: 'REAL', TEXT: 'TEXT' };
}

/**
 * Add a column unless it is already there.
 *
 * Exists for databases created before the migration table did: their tables
 * may or may not already have a column depending on which checkout made them.
 */
export async function addColumnIfMissing(
  ctx: MigrationContext, table: string, column: string, definition: string,
): Promise<void> {
  if (await ctx.columnExists(table, column)) return;
  await ctx.exec(`ALTER TABLE ${table} ADD COLUMN ${column} ${definition}`);
}

